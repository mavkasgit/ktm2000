/**
 * Размеры модальных окон интерфейса оператора.
 *
 * Оверлей, центрирование, удержание фокуса, закрытие по Escape и возврат фокуса
 * задаёт общий каркас `Dialog` (`shared/ui/dialog.tsx`). Здесь — только размер,
 * потому что окна по содержимому разного масштаба: подтверждение, панель
 * настроек, широкая таблица плана.
 *
 * Свои ширины рядом с окном не объявляются. Отдельная таблица может уточнить
 * общий набор `TABLE_ROW_COMPACT` только рядом с собой и поверх него; здесь то
 * же: `{ ...DIALOG_SIZES.wide, ...overrides }`.
 *
 * Правило — ADR-0033.
 */

/** Ширина и высота окна. `maxHeight` ограничивает окно, содержимое скроллится. */
export type DialogSize = {
  /** Классы ширины окна. */
  width: string;
  /** Классы высоты окна. */
  height: string;
};

export const DIALOG_SIZES = {
  /** Подтверждение, короткая форма, выбор из списка. */
  sm: { width: "w-[92vw] max-w-[420px]", height: "max-h-[90vh]" },
  /** Панель настроек с полями и переключателями. */
  md: { width: "w-[92vw] max-w-[640px]", height: "max-h-[90vh]" },
  /** Таблицы и предпросмотр печати: нужен горизонтальный простор. */
  wide: { width: "w-[92vw] max-w-[1500px]", height: "max-h-[92vh]" },
} as const satisfies Record<string, DialogSize>;

export type DialogSizeName = keyof typeof DIALOG_SIZES;
