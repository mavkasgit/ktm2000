/**
 * Фоновый опрос операционных экранов (фаза 2 свежести, тикет #206).
 *
 * Решение владельца (гриллинг 2026-10-01, `docs/night/PLAN-2026-10-01.md` §5):
 * пока числа замера #208 держат «меньше ~1 запроса/с на терминал», механизм
 * «чужие изменения видны без F5» — polling 10–15 с на 2–3 операционных экранах
 * через `refetchInterval`. Это исключение названо поимённо в ADR-0041.
 *
 * ## Почему это не второй механизм сброса кэша
 *
 * `refetchInterval` перечитывает тот же `useQuery`, что уже смонтирован на
 * экране: ключ не меняется, реестр `cacheInvalidation.ts` не обходится.
 * Сброс кэша после бизнес-действий остаётся единственным — `invalidateDomains`;
 * опрос лишь повторяет запрос по таймеру. Второго способа инвалидации здесь
 * нет.
 *
 * ## Почему интервал именно такой
 *
 * 12 с — середина разрешённого владельцем коридора 10–15 с. Нижняя граница
 * 10 с удвоила бы трафик ради выигрыша в несколько секунд на действии чужого
 * терминала; верхняя 15 с держала бы изменение коллеги до четверти минуты.
 * Замер #208 показал, что смена экрана — это промах кеша, не зависящий от
 * `staleTime`; опрос добавляет к проходу не более одного перечитывания
 * основного списка за интервал, пока вкладка в фокусе.
 *
 * ## Почему фон не опрашивается
 *
 * `refetchIntervalInBackground: false` (и дефолт TanStack, здесь выписан явно,
 * потому что это часть правила) — свёрнутая вкладка не ходит на сервер:
 * оператор, который её не видит, изменений всё равно не увидит, а трафик
 * терминала умножился бы на число открытых вкладок.
 */

/**
 * Интервал опроса операционного экрана, мс. Одно значение на все исключения
 * ADR-0041: менять его нужно в одном месте и вместе с ADR.
 */
export const OPERATIONAL_POLL_INTERVAL_MS = 12_000;

/**
 * Опции `useQuery` для операционного экрана. Разворачиваются в существующий
 * запрос: `{ ...operationalPollingOptions }` — новый `useQuery` не заводится.
 */
export const operationalPollingOptions = {
  refetchInterval: OPERATIONAL_POLL_INTERVAL_MS,
  refetchIntervalInBackground: false,
} as const;
