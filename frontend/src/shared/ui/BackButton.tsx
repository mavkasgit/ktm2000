import { ArrowLeft } from "lucide-react";
import { useNavigate } from "react-router-dom";

import { Button } from "./button";

/**
 * Кнопка возврата к родительскому экрану.
 *
 * Безымянная иконка в сайдбаре возврата нет: подпись «куда» не помещается
 * рядом с длинными заголовками, а всплывающая подсказка её не заменяет — на
 * тач-экране `title` не читается. Имя остаётся в `aria-label` (его читает
 * скринридер), название раздела — в `title`.
 *
 * Цель обязательна и всегда явная. Кнопка, уводящая через `history.back()`,
 * при прямом заходе по ссылке или после перезагрузки страницы не делает
 * ничего — а на экране может быть единственным выходом.
 *
 * Не путать с кнопкой «Назад» внутри мастеров: там возврат на шаг, а не на
 * маршрут, и выглядит она как обычная кнопка подтверждения.
 */
export function BackButton({
  to,
  title = "Назад",
}: {
  /** Маршрут родительского экрана. */
  to: string;
  /** Подсказка: название раздела, куда ведёт кнопка. */
  title?: string;
}) {
  const navigate = useNavigate();

  return (
    <Button
      variant="ghost"
      size="icon"
      aria-label="Назад"
      title={title}
      className="shrink-0"
      onClick={() => navigate(to)}
    >
      <ArrowLeft className="h-5 w-5" />
    </Button>
  );
}