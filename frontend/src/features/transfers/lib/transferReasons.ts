/**
 * Причины недоступности передачи (#193, ревью #341).
 *
 * «Нечего передавать» — одно правило, а мест, где оно применяется, три: строка
 * «Готово к передаче», шапка группы и футер массового ввода. До выноса оно было
 * написано трижды рядом с кнопками; расхождение в одной цифре означало бы, что
 * оператор видит в одном из мест другую причину (или кнопка становится
 * нажимable без числа). Здесь только «число → причина»: остальные причины
 * (`row_in_flight`, `no_executor`, `final_release_not_in_bulk`) живут там, где
 * они известны.
 */

import type { ActionReasonCode } from "@/shared/lib/actionReasons";

/**
 * Причина, по которой передача не нажимается из-за количества.
 *
 * Передать можно строго больше нуля: ноль, отрицательное число и `NaN`
 * (пустое или мусор в поле — `parseFloat("")` даёт именно `NaN`) означают, что
 * ввода нет. Положительное дробное количество законно: колонка дробная
 * (`Numeric(14,3)`), поэтому сравнение с нулём, а не проверка целочисленности.
 */
export function zeroQuantityReason(qty: number): ActionReasonCode | null {
  return qty > 0 ? null : "zero_quantity";
}
